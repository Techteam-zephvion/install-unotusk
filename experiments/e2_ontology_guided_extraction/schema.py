"""
E2 Candidate Ontology Proposal Schema Specification.
Part of Unotusk AI-PIE Code Lane Research Proof of Concept (OntoRAG arXiv:2506.00664).

GOVERNANCE REQUIREMENT:
All candidate ontology concepts, relations, and taxonomies generated by E2
are strictly PROPOSED_PENDING_REVIEW. The production V1 ontology is immutable
and must not be modified or superseded without formal architectural review sign-off.
"""

import uuid
from datetime import UTC, datetime
from enum import Enum
from typing import Any

from pydantic import BaseModel, ConfigDict, Field, field_validator


class ProposalStatus(str, Enum):
    """Governance lifecycle status for candidate ontology artifacts."""

    PROPOSED_PENDING_REVIEW = "PROPOSED_PENDING_REVIEW"
    ACCEPTED = "ACCEPTED"
    REJECTED = "REJECTED"


class OntologyCategory(str, Enum):
    """High-level architectural categories for induced code concepts."""

    DOMAIN_SUBSYSTEM = "DOMAIN_SUBSYSTEM"
    SERVICE_COMPONENT = "SERVICE_COMPONENT"
    DATA_ACCESS = "DATA_ACCESS"
    SECURITY_VALIDATION = "SECURITY_VALIDATION"
    INFRASTRUCTURE_CONFIG = "INFRASTRUCTURE_CONFIG"
    OPERATION_MEMBER = "OPERATION_MEMBER"
    OTHER = "OTHER"


class CandidateRelationType(str, Enum):
    """Architectural and semantic relationships binding candidate concepts."""

    SPECIALIZES = "SPECIALIZES"      # Subtype or inheritance relationship (is-a)
    COMPOSED_OF = "COMPOSED_OF"      # Structural composition or containment (has-a)
    DEPENDS_ON = "DEPENDS_ON"        # Dependency injection or import binding
    CALLS = "CALLS"                  # Direct execution invocation
    MANAGES = "MANAGES"              # Lifecycle management or entity orchestration
    CONFIGURES = "CONFIGURES"        # Setting or parameter application
    VALIDATES = "VALIDATES"          # Schema or state assertion
    MODIFIES = "MODIFIES"            # State mutation or data transformation
    TESTS = "TESTS"                  # Verification and test coverage


class EvidenceProvenance(BaseModel):
    """Immutable, traceable source evidence grounding a proposed concept or relation."""

    file_path: str
    start_line: int | None = None
    end_line: int | None = None
    commit_sha: str | None = None
    diff_snippet: str = ""
    symbol_name: str | None = None
    grounded_tokens: list[str] = Field(default_factory=list)

    model_config = ConfigDict(extra="ignore")


class CandidateConcept(BaseModel):
    """
    Candidate ontology concept induced from Code Lane evidence.
    Always generated with PROPOSED_PENDING_REVIEW status.
    """

    concept_id: str = Field(default_factory=lambda: f"concept_{uuid.uuid4().hex[:12]}")
    name: str
    category: OntologyCategory = OntologyCategory.SERVICE_COMPONENT
    parent_concept_id: str | None = None
    description: str = ""
    source_entity_names: list[str] = Field(default_factory=list)
    source_entity_types: list[str] = Field(default_factory=list)
    confidence: float = Field(default=0.8, ge=0.0, le=1.0)
    status: ProposalStatus = ProposalStatus.PROPOSED_PENDING_REVIEW
    evidence: list[EvidenceProvenance] = Field(default_factory=list)
    attributes: dict[str, Any] = Field(default_factory=dict)
    v1_base_mapping: str | None = None

    model_config = ConfigDict(extra="ignore")

    @field_validator("confidence")
    @classmethod
    def validate_confidence(cls, v: float) -> float:
        if v < 0.0 or v > 1.0:
            raise ValueError(f"Confidence must be between 0.0 and 1.0, got {v}")
        return round(float(v), 4)


class CandidateRelation(BaseModel):
    """
    Candidate semantic relationship between two candidate ontology concepts.
    Always generated with PROPOSED_PENDING_REVIEW status.
    """

    relation_id: str = Field(default_factory=lambda: f"rel_{uuid.uuid4().hex[:12]}")
    subject_concept_id: str
    relation_type: CandidateRelationType = CandidateRelationType.DEPENDS_ON
    object_concept_id: str
    confidence: float = Field(default=0.8, ge=0.0, le=1.0)
    status: ProposalStatus = ProposalStatus.PROPOSED_PENDING_REVIEW
    evidence: list[EvidenceProvenance] = Field(default_factory=list)
    is_exclusive: bool = False

    model_config = ConfigDict(extra="ignore")

    @field_validator("confidence")
    @classmethod
    def validate_confidence(cls, v: float) -> float:
        if v < 0.0 or v > 1.0:
            raise ValueError(f"Confidence must be between 0.0 and 1.0, got {v}")
        return round(float(v), 4)


class TaxonomyNode(BaseModel):
    """Hierarchical node representing a level in the induced concept taxonomy."""

    concept_id: str
    name: str
    category: str
    level: int = 0
    children: list["TaxonomyNode"] = Field(default_factory=list)

    model_config = ConfigDict(extra="ignore")


class OntologyProposal(BaseModel):
    """
    Complete candidate ontology proposal package containing induced concepts,
    relationships, taxonomy hierarchy, and governance metadata.
    """

    proposal_id: str = Field(default_factory=lambda: f"proposal_{uuid.uuid4().hex[:12]}")
    created_at: datetime = Field(default_factory=lambda: datetime.now(UTC))
    concepts: list[CandidateConcept] = Field(default_factory=list)
    relations: list[CandidateRelation] = Field(default_factory=list)
    taxonomy_roots: list[TaxonomyNode] = Field(default_factory=list)
    clustering_threshold: float = 0.70
    metrics: dict[str, Any] = Field(default_factory=dict)
    v1_compatibility_notes: str = (
        "Strictly additive proposal. Retains V1 compatibility by mapping to "
        "base EntityType and RelationType while proposing specialized architectural concepts."
    )
    governance_disclaimer: str = (
        "PROVISIONAL EXPERIMENTAL ARTIFACT: All candidate concepts and relations are "
        "PROPOSED_PENDING_REVIEW. The production V1 ontology remains immutable."
    )

    model_config = ConfigDict(extra="ignore")
